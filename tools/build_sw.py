#!/usr/bin/env python3
"""Writes sw.js: the service worker that saves every app file on the device
so the game works with no internet. Re-run after changing any app file:
    python3 tools/build_sw.py
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INCLUDE_DIRS = ['css', 'js', 'vendor', 'assets']
INCLUDE_FILES = ['index.html', 'manifest.webmanifest']
SKIP_SUFFIX = ('.map', '.md', '.txt', 'LICENSE')

files = list(INCLUDE_FILES)
for d in INCLUDE_DIRS:
    for p in sorted((ROOT / d).rglob('*')):
        if p.is_file() and not p.name.endswith(SKIP_SUFFIX) and not p.name.startswith('.'):
            files.append(p.relative_to(ROOT).as_posix())

h = hashlib.sha256()
for f in files:
    h.update(f.encode())
    h.update((ROOT / f).read_bytes())
version = h.hexdigest()[:12]

sw = f"""// Generated by tools/build_sw.py - do not edit by hand.
// Saves the whole app on the device so it works offline.
const CACHE = 'chess-{version}';
const FILES = {json.dumps(['./'] + files, indent=2)};

self.addEventListener('install', (event) => {{
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES.map((f) => new Request(f, {{ cache: 'reload' }}))))
      .then(() => self.skipWaiting()),
  );
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('chess-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
}});

// Offline first: answer from the saved copy, fall back to the network.
self.addEventListener('fetch', (event) => {{
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, {{ ignoreSearch: true }}).then((hit) => {{
      if (hit) return hit;
      if (req.mode === 'navigate') return caches.match('./index.html').then((r) => r || fetch(req));
      return fetch(req);
    }}),
  );
}});
"""
(ROOT / 'sw.js').write_text(sw)
total = sum((ROOT / f).stat().st_size for f in files)
print(f'sw.js: {len(files)} files, {total / 1e6:.1f} MB, cache chess-{version}')
