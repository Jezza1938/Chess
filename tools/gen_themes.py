#!/usr/bin/env python3
"""Generates css/themes.css for the boards and piece sets, plus upside-down
copies of the black pieces (used by the face-to-face option in 2-player games).

Run from the repo root:  python3 tools/gen_themes.py
"""
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BOARDS = ['brown', 'green', 'blue', 'purple', 'wood', 'maple', 'marble', 'blue-marble', 'metal', 'leather']
PIECES = ['cburnett', 'merida', 'alpha', 'california', 'staunty', 'cardinal', 'fantasy', 'celtic', 'spatial', 'pixel']
ROLES = {'P': 'pawn', 'N': 'knight', 'B': 'bishop', 'R': 'rook', 'Q': 'queen', 'K': 'king'}


def board_file(name):
    for ext in ('png', 'jpg'):
        p = ROOT / 'assets' / 'boards' / f'{name}.{ext}'
        if p.exists():
            return p
    raise FileNotFoundError(name)


def sample(img, fx, fy):
    """Average colour of a small patch around (fx, fy) given as fractions."""
    w, h = img.size
    cx, cy = int(fx * w), int(fy * h)
    r = max(2, w // 64)
    patch = img.crop((cx - r, cy - r, cx + r, cy + r)).resize((1, 1), Image.LANCZOS)
    return '#%02x%02x%02x' % patch.getpixel((0, 0))[:3]


def rotate_svg(src: Path, dst: Path):
    text = src.read_text()
    m = re.search(r'<svg\b[^>]*>', text)
    if not m:
        raise ValueError(f'no <svg> in {src}')
    tag = m.group(0)
    vb = re.search(r'viewBox="([^"]+)"', tag)
    if vb:
        x, y, w, h = [float(v) for v in re.split(r'[ ,]+', vb.group(1).strip())]
    else:
        w = float(re.search(r'width="([\d.]+)', tag).group(1))
        h = float(re.search(r'height="([\d.]+)', tag).group(1))
        x = y = 0.0
    cx, cy = x + w / 2, y + h / 2
    end = text.rindex('</svg>')
    body = text[m.end():end]
    out = text[:m.end()] + f'<g transform="rotate(180 {cx:g} {cy:g})">' + body + '</g>' + text[end:]
    dst.write_text(out)


def main():
    css = ['/* Generated by tools/gen_themes.py - do not edit by hand. */']
    for b in BOARDS:
        f = board_file(b)
        img = Image.open(f).convert('RGB')
        # a8 (top-left) is a light square, b8 next to it is dark.
        light = sample(img, 1 / 16, 1 / 16)
        dark = sample(img, 3 / 16, 1 / 16)
        # Checkerboard thumbnail for the picker: the top-left 4x4 squares.
        thumbs = ROOT / 'assets' / 'boards' / 'thumbs'
        thumbs.mkdir(exist_ok=True)
        w, h = img.size
        img.crop((0, 0, w // 2, h // 2)).resize((200, 200), Image.LANCZOS).save(thumbs / f'{b}.jpg', quality=86)
        css.append(
            f'.board-{b} cg-board {{ background-image: url(../assets/boards/{f.name}); background-color: {dark}; }}\n'
            f'.board-{b} {{ --sq-light: {light}; --sq-dark: {dark}; }}'
        )
    for s in PIECES:
        d = ROOT / 'assets' / 'pieces' / s
        for color, c in (('white', 'w'), ('black', 'b')):
            for code, role in ROLES.items():
                css.append(f'.pieces-{s} piece.{color}.{role} {{ background-image: url(../assets/pieces/{s}/{c}{code}.svg); }}')
        for code, role in ROLES.items():
            rotate_svg(d / f'b{code}.svg', d / f'r-b{code}.svg')
            css.append(
                f'.face-to-face.pieces-{s} .cg-wrap piece.black.{role} '
                f'{{ background-image: url(../assets/pieces/{s}/r-b{code}.svg); }}'
            )
    (ROOT / 'css' / 'themes.css').write_text('\n'.join(css) + '\n')
    print('wrote css/themes.css')


if __name__ == '__main__':
    main()
